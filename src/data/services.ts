/* -------------------------------------------------------------------------- */
/* Helpers                                                                    */
/* -------------------------------------------------------------------------- */

export function liveServices(group: ServiceGroup) {
  return group.services;
}

export function serviceHref(_group: ServiceGroup, service: Service) {
  return `/services/${service.slug}`;
}

export function getGroup(slug: string) {
  return serviceGroups.find((g) => g.slug === slug);
}

export function allServices() {
  return serviceGroups.flatMap((group) => group.services.map((service) => ({ group, service })));
}

export function findServiceBySlug(slug: string) {
  return allServices().find(({ service }) => service.slug === slug) ?? null;
}
