-- Creates jobs (if missing) then job_applications.

create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  title text not null,
  department text not null default '',
  employment_type text not null default 'Full-time',
  work_mode text not null default 'Hybrid',
  location text not null default '',
  summary text not null default '',
  about text not null default '',
  responsibilities text[] not null default '{}',
  requirements text[] not null default '{}',
  benefits text[] not null default '{}',
  posted_at date not null default current_date,
  hidden boolean not null default false
);

alter table public.jobs enable row level security;
create index if not exists jobs_sort_idx on public.jobs (sort_order);

drop index if exists public.jobs_slug_idx;
alter table public.jobs drop column if exists slug;

create table if not exists public.job_applications (
  id bigint generated by default as identity primary key,
  job_id bigint references public.jobs (id) on delete set null,
  job_title text not null,
  first_name text not null,
  last_name text not null,
  email text not null,
  phone text not null default '',
  address text not null default '',
  linkedin text not null default '',
  website text not null default '',
  cover_letter text not null default '',
  education jsonb not null default '[]'::jsonb,
  experience jsonb not null default '[]'::jsonb,
  resume_name text not null default '',
  resume_url text not null default '',
  resume_path text not null default '',
  status text not null default 'new',
  created_at timestamptz not null default now()
);

alter table public.job_applications enable row level security;

create index if not exists job_applications_created_idx on public.job_applications (created_at desc);
create index if not exists job_applications_job_idx on public.job_applications (job_id);
create index if not exists job_applications_status_idx on public.job_applications (status);
