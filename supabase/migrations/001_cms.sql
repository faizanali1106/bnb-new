create index if not exists projects_sort_idx on public.projects (sort_order);
create index if not exists testimonials_sort_idx on public.testimonials (sort_order);
create index if not exists work_experience_sort_idx on public.work_experience (sort_order);
create index if not exists companies_sort_idx on public.companies (sort_order);
create index if not exists social_media_sort_idx on public.social_media (sort_order);
create index if not exists grid_items_sort_idx on public.grid_items (sort_order);
