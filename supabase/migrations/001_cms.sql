-- Run this in Supabase: SQL Editor → New query → Paste → Run.
-- Creates CMS tables for the portfolio site.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  title text not null,
  des text not null,
  img text not null,
  link text not null default '/portfolio',
  icon_slugs text[] not null default '{}'
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  quote text not null,
  name text not null,
  title text not null default ''
);

create table if not exists public.work_experience (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  title text not null,
  description text not null,
  class_name text not null default 'md:col-span-2',
  thumbnail text not null
);

create table if not exists public.grid_items (
  id bigint primary key,
  sort_order int not null default 0,
  title text not null,
  description text not null default '',
  class_name text not null,
  img text not null default '',
  img_class_name text not null default '',
  title_class_name text not null default '',
  spare_img text not null default ''
);

create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  name text not null,
  img text not null,
  name_img text not null
);

create table if not exists public.social_media (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  name text not null,
  img text not null default '',
  url text not null,
  display text,
  use_lucide_mail boolean not null default false
);

create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null
);

alter table public.projects enable row level security;
alter table public.testimonials enable row level security;
alter table public.work_experience enable row level security;
alter table public.grid_items enable row level security;
alter table public.companies enable row level security;
alter table public.social_media enable row level security;
alter table public.site_settings enable row level security;

